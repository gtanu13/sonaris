/** Aggregate distribution used by summary widgets. */
export function summarizeDetections(detections: Detection[]) {
  return {
    total: detections.length,
    known: detections.filter((d) => d.detectionStatus === "KNOWN OBJECT").length,
    unknown: detections.filter((d) => d.detectionStatus === "UNKNOWN ANOMALY").length,
    highPriority: detections.filter((d) => d.risk === "high").length,
  };
}
