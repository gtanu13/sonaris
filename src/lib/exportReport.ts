export function exportReportPDF(survey: SurveyMeta, topTargets: Detection[]) {
  const win = window.open("", "_blank");
  if (!win) return;
  win.document.write(reportHtml(survey, topTargets));
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 300);
}
