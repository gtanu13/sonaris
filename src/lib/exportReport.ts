import type { Detection } from "@/data/demoDetections";
import type { SurveyMeta } from "@/data/demoSurvey";

function downloadBlob(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function exportDetectionsCSV(survey: SurveyMeta, detections: Detection[]) {
  const header = [
    "Target ID",
    "Classification",
    "Status",
    "Latitude",
    "Longitude",
    "Depth (m)",
    "Length (m)",
    "Width (m)",
    "Height (m)",
    "Anomaly Score",
    "Confidence",
    "Risk",
  ];
  const rows = detections.map((d) => [
    d.id,
    d.classification,
    d.detectionStatus,
    d.latitude.toFixed(4),
    d.longitude.toFixed(4),
    d.depth.toFixed(1),
    d.length.toFixed(2),
    d.width.toFixed(2),
    d.height.toFixed(2),
    Math.round(d.anomalyScore * 100),
    Math.round(d.confidence * 100),
    d.risk,
  ]);
  const csv = [header, ...rows].map((r) => r.map((v) => `"${v}"`).join(",")).join("\n");
  downloadBlob(csv, `${survey.id}-detections.csv`, "text/csv;charset=utf-8;");
}

